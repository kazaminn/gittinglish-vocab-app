/**
 * The published policy and terms, transcribed verbatim.
 *
 * Held as data rather than as JSX prose for one reason: JSX wraps long lines,
 * and a line break inside a Japanese sentence renders as a space the document
 * does not contain. These are the operator's words — when the app stops
 * matching them the app is what is wrong — so they are stored where nothing
 * can reformat them, and the page only lays them out.
 */

